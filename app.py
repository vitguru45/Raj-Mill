            st.caption("From a tap test: natural frequency, damping ratio and modal "
                       "stiffness of the dominant mode in each direction.")
            c1, c2, c3 = st.columns(3)
            fx = c1.number_input("fn x (Hz)", 10.0, 50000.0, 800.0, 10.0)
