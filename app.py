@dataclass
class StabilityResult:
    speeds_rpm: np.ndarray            # one row per lobe number
    depths_mm: np.ndarray             # matching limiting axial depths
    lobes: np.ndarray                 # lobe index for each point
    chatter_hz: np.ndarray            # chatter frequency at each point
    n_grid: np.ndarray = field(default_factory=lambda: np.empty(0))
    alim_grid: np.ndarray = field(default_factory=lambda: np.empty(0))
    n_reliable_min: float = 0.0
    """Below this speed the lobes are closer together than the speed grid can
    resolve, so the envelope there is aliasing rather than physics. Low speeds
    are also where process damping makes real cuts more stable than this model
    predicts, so both effects say the same thing: do not trust it down there."""

    def limit_at(self, n_rpm: float) -> float:
        """Limiting depth of cut at one spindle speed, mm."""
        if self.n_grid.size == 0:
            return float("nan")
        return float(np.interp(n_rpm, self.n_grid, self.alim_grid))


def stability_lobes(dyn: ToolDynamics, *, teeth: int, Kt: float, Kr: float,
                    phi_st: float, phi_ex: float, n_lobes: int = 12,
                    freq_points: int = 6000,
                    freq_span: tuple[float, float] | None = None,
                    n_range: tuple[float, float] = (500, 30000),
                    n_points: int = 1200) -> StabilityResult:
    """Sweep chatter frequency, solve for the limiting depth and the speeds."""
    fns = dyn.frequencies
    lo, hi = freq_span or (0.35 * min(fns), 2.2 * max(fns))
    fc = np.linspace(max(1.0, lo), hi, freq_points)
    omega = 2 * np.pi * fc

    Pxx = dyn.phi_xx(omega)
    Pyy = dyn.phi_yy(omega)
    axx, axy, ayx, ayy = directional_coefficients(phi_st, phi_ex, Kr)

    # a0 * L^2 + a1 * L + 1 = 0
    a0 = Pxx * Pyy * (axx * ayy - axy * ayx)
    a1 = axx * Pxx + ayy * Pyy
    disc = np.sqrt(np.where(np.abs(a0) > 0, a1 ** 2 - 4 * a0, a1 ** 2 + 0j))

    speeds, depths, lobe_ids, freqs = [], [], [], []
    grid = np.linspace(n_range[0], n_range[1], n_points)
    branch_curves: list[np.ndarray] = []

    for sign in (+1, -1):                    # both roots of the quadratic
        with np.errstate(divide="ignore", invalid="ignore"):
            L = np.where(np.abs(a0) > 1e-30, (-a1 + sign * disc) / (2 * a0), -1.0 / a1)
        LR, LI = np.real(L), np.imag(L)
        kappa = LI / LR
        # Kt in N/mm^2 and receptance in m/N: the 1e-3 converts the depth to mm
        alim = -2 * np.pi * LR * (1 + kappa ** 2) / (teeth * Kt) * 1e-3
        eps = np.pi - 2 * np.arctan(kappa)
        for k in range(n_lobes + 1):
            T = (eps + 2 * np.pi * k) / omega          # tooth period, s
            n = 60.0 / (teeth * T)
            ok = (alim > 0) & np.isfinite(alim) & (n > n_range[0]) & (n < n_range[1])
            if ok.sum() < 3:
                continue
            speeds.append(n[ok]); depths.append(alim[ok])
            lobe_ids.append(np.full(ok.sum(), k)); freqs.append(fc[ok])
            branch_curves.append(_branch_on_grid(n[ok], alim[ok], grid))

    n_all = np.concatenate(speeds) if speeds else np.empty(0)
    a_all = np.concatenate(depths) if depths else np.empty(0)
    k_all = np.concatenate(lobe_ids) if lobe_ids else np.empty(0)
    f_all = np.concatenate(freqs) if freqs else np.empty(0)

    # The usable boundary is the lowest branch at each speed. Each branch is
    # interpolated onto the grid over the span it actually covers, so a sparsely
    # sampled branch cannot punch single-cell holes in the envelope.
    if branch_curves:
        stack = np.vstack(branch_curves)
        with warnings.catch_warnings():       # columns no branch covers are all-NaN
            warnings.simplefilter("ignore", RuntimeWarning)
            env = np.nanmin(stack, axis=0)
        env = _fill_gaps(np.where(np.isfinite(env), env, np.inf))
    else:
        env = np.zeros(n_points)
    step = grid[1] - grid[0]
    fn_min = min(dyn.frequencies)
    reliable = float(np.sqrt(20 * step * 60 * fn_min / teeth))
    return StabilityResult(speeds_rpm=n_all, depths_mm=a_all, lobes=k_all,
                           chatter_hz=f_all, n_grid=grid, alim_grid=env,
                           n_reliable_min=min(reliable, grid[-1]))


def _branch_on_grid(n: np.ndarray, a: np.ndarray, grid: np.ndarray) -> np.ndarray:
    """One lobe branch resampled onto the speed grid, NaN outside its own span."""
    order = np.argsort(n)
    ns, as_ = n[order], a[order]
    # a branch can fold back on itself in speed; keep the lower depth per speed
    uniq, inv = np.unique(np.round(ns, 6), return_inverse=True)
    low = np.full(uniq.size, np.inf)
    np.minimum.at(low, inv, as_)
    out = np.interp(grid, uniq, low, left=np.nan, right=np.nan)
    return np.where((grid >= uniq[0]) & (grid <= uniq[-1]), out, np.nan)


def _fill_gaps(env: np.ndarray) -> np.ndarray:
    """Interpolate grid cells that no lobe point landed in."""
    finite = np.isfinite(env)
    if not finite.any():
        return np.zeros_like(env)
    idx = np.arange(len(env))
    return np.interp(idx, idx[finite], env[finite])


def chatter_frequency_at(res: StabilityResult, n_rpm: float) -> float:
    """Frequency the chatter would grow at, for the speed given."""
    if res.speeds_rpm.size == 0:
        return float("nan")
    near = np.abs(res.speeds_rpm - n_rpm) < max(25.0, 0.01 * n_rpm)
    if not near.any():
        near = np.abs(res.speeds_rpm - n_rpm) == np.abs(res.speeds_rpm - n_rpm).min()
    sel = np.argmin(res.depths_mm[near])
    return float(res.chatter_hz[near][sel])


# --------------------------------------------------------------------------
# Working with an operating point
# --------------------------------------------------------------------------

def tooth_passing_hz(n_rpm: float, teeth: int) -> float:
    return n_rpm * teeth / 60.0


def material_removal_rate(ap_mm: float, ae_mm: float, feed_mm_min: float) -> float:
    """MRR in mm^3/min."""
    return ap_mm * ae_mm * feed_mm_min


def stable_speed_suggestions(res: StabilityResult, ap_mm: float, n_rpm: float,
                             n_max: int = 3, margin: float = 1.2) -> list[dict]:
    """Speeds near the current one where the limit clears the depth being used.

    Returns the peak of each usable stability pocket, closest first.
    """
    n, a = res.n_grid, res.alim_grid
    usable = (a >= ap_mm * margin) & (n >= res.n_reliable_min)
    if not usable.any():
        return []
    # contiguous runs of usable speeds = stability pockets
    padded = np.r_[False, usable, False]
    starts = np.flatnonzero(~padded[:-1] & padded[1:])
    ends = np.flatnonzero(padded[:-1] & ~padded[1:]) - 1
    out = []
    step = n[1] - n[0]
    for s, e in zip(starts, ends):
        if e - s < 2:                       # ignore single-cell jitter
            continue
        best = s + int(np.argmax(a[s:e + 1]))
        nearest = int(np.clip(np.searchsorted(n, n_rpm), s, e))
        out.append({"speed_rpm": float(n[best]), "limit_mm": float(a[best]),
                    "nearest_rpm": float(n[nearest]),
                    "nearest_limit_mm": float(a[nearest]),
                    "from_rpm": float(n[s]), "to_rpm": float(n[e]),
                    "width_rpm": float(n[e] - n[s] + step),
                    "distance_rpm": float(abs(n[nearest] - n_rpm))})
    out.sort(key=lambda d: d["distance_rpm"])
    return out[:n_max]


# -------------------------------------------------------------------------
# core/roughness.py
# -------------------------------------------------------------------------
# Expected surface roughness from the cutting geometry.
#
# The geometric part is exact: it is the height of the material left between
# successive tool marks. The rest is honest correction factors, each one reported
# separately so you can see what the number is made of rather than trusting a
# single figure.
#
# Real Ra is almost always above the geometric value — tool wear, built-up edge,
# side flow, runout and residual vibration all add to it. A process factor of
# about 1.5 to 2.5 is typical for a well-behaved cut.



# ISO 1302 roughness grades, Ra in micrometres
ISO_GRADES = {"N1": 0.025, "N2": 0.05, "N3": 0.1, "N4": 0.2, "N5": 0.4, "N6": 0.8,
              "N7": 1.6, "N8": 3.2, "N9": 6.3, "N10": 12.5, "N11": 25.0, "N12": 50.0}

OPERATIONS = ["Face milling / turning (nose radius)",
              "Peripheral milling (flat end mill)",
              "Ball-nose finishing (stepover)"]


@dataclass
class RoughnessResult:
    ra_geometric_um: float
    ra_expected_um: float
    rz_geometric_um: float
    effective_feed_mm: float
    factors: dict[str, float] = field(default_factory=dict)
    notes: list[str] = field(default_factory=list)
    chatter_range_um: tuple[float, float] | None = None

    @property
    def grade(self) -> str:
        for name, value in ISO_GRADES.items():
            if self.ra_expected_um <= value:
                return name
        return "coarser than N12"


def effective_feed(fz_mm: float, teeth: int, runout_mm: float) -> tuple[float, float]:
    """Feed between consecutive marks once runout is accounted for.

    With no runout every tooth cuts the same chip and the marks are fz apart.
    Once the radial throw of one tooth exceeds the feed per tooth, that tooth
    does all the cutting and the marks open out towards the feed per revolution.
    """
    if runout_mm <= 0 or teeth <= 1:
        return fz_mm, 0.0
    share = float(min(1.0, runout_mm / max(fz_mm, 1e-9)))
    return fz_mm * (1 + share * (teeth - 1)), share


def roughness(operation: str, *, fz_mm: float, teeth: int, diameter_mm: float,
              nose_radius_mm: float = 0.8, stepover_mm: float = 0.5,
              runout_mm: float = 0.0, process_factor: float = 1.8,
              edge_radius_um: float | None = None,
              unstable: bool = False) -> RoughnessResult:
    f_eff, runout_share = effective_feed(fz_mm, teeth, runout_mm)
    notes: list[str] = []
    factors: dict[str, float] = {}

    if operation.startswith("Face"):
        rz = f_eff ** 2 / (8 * max(nose_radius_mm, 1e-6)) * 1e3     # mm -> um
        ra = f_eff ** 2 / (32 * max(nose_radius_mm, 1e-6)) * 1e3
        notes.append("Geometric part: marks left by the nose radius, "
                     "Rz = f²/(8r), Ra = f²/(32r).")
    elif operation.startswith("Peripheral"):
        R = max(diameter_mm / 2, 1e-6)
        rz = f_eff ** 2 / (8 * R) * 1e3
        ra = rz / 4
        notes.append("Geometric part: cusps left by the circular tooth path on the "
                     "wall, Rz ≈ fz²/(8R) with R the cutter radius.")
    else:
        R = max(diameter_mm / 2, 1e-6)
        h = R - np.sqrt(max(R ** 2 - (stepover_mm / 2) ** 2, 0.0))
        rz = h * 1e3
        ra = rz / 4
        notes.append("Geometric part: scallop height between passes, "
                     "h = R − √(R² − (ae/2)²). Stepover drives this, not feed.")

    ra_expected = ra
    if runout_share > 0:
        factors["runout"] = f_eff / max(fz_mm, 1e-9)
        notes.append(f"Runout of {runout_mm * 1000:.0f} µm opens the mark spacing from "
                     f"{fz_mm:.4f} to {f_eff:.4f} mm/mark.")

    # Minimum chip thickness: below roughly a quarter of the edge radius the
    # edge ploughs instead of cutting, and the finish degrades sharply. This
    # matters in micro-milling, where fz and the edge radius are comparable.
    if edge_radius_um:
        h_min_mm = 0.25 * edge_radius_um * 1e-3
        if fz_mm < h_min_mm:
            k = float(np.sqrt(h_min_mm / max(fz_mm, 1e-9)))
            factors["ploughing"] = k
            ra_expected *= k
            notes.append(
                f"Feed per tooth ({fz_mm * 1000:.1f} µm) is below the minimum chip "
                f"thickness (~{h_min_mm * 1000:.1f} µm for a {edge_radius_um:.0f} µm "
                "edge radius), so the edge ploughs and rubs. Heuristic penalty applied.")

    factors["process"] = process_factor
    ra_expected *= process_factor

    chatter_range = None
    if unstable:
        chatter_range = (ra_expected * 3, ra_expected * 10)
        notes.append("The cut is predicted to be unstable, so this figure is only a "
                     "floor: chatter marks set the finish instead of the feed marks. "
                     "Measured Ra under chatter is typically three to ten times the "
                     "stable value, with visible waviness.")

    return RoughnessResult(ra_geometric_um=float(ra), ra_expected_um=float(ra_expected),
                           rz_geometric_um=float(rz), effective_feed_mm=float(f_eff),
                           factors=factors, notes=notes, chatter_range_um=chatter_range)


def feed_for_target_ra(operation: str, target_ra_um: float, *, teeth: int,
                       diameter_mm: float, nose_radius_mm: float,
                       process_factor: float) -> float | None:
    """Feed per tooth that would just meet a target Ra, ignoring runout."""
    ra = target_ra_um / max(process_factor, 1e-6)
    if operation.startswith("Face"):
        return float(np.sqrt(ra * 32 * nose_radius_mm * 1e-3))
    if operation.startswith("Peripheral"):
        return float(np.sqrt(ra * 4 * 8 * (diameter_mm / 2) * 1e-3))
    return None            # ball-nose finish is set by stepover, not feed


def stepover_for_target_ra(target_ra_um: float, diameter_mm: float,
                           process_factor: float) -> float:
    """Stepover that would just meet a target Ra in ball-nose finishing."""
    R = diameter_mm / 2
    h = target_ra_um / max(process_factor, 1e-6) * 4 * 1e-3      # um -> mm
    h = min(h, R * 0.999)
    return float(2 * np.sqrt(max(R ** 2 - (R - h) ** 2, 0.0)))


# -------------------------------------------------------------------------
# core/recommend.py
# -------------------------------------------------------------------------
# Turn the stability and roughness results into a verdict and a set of moves.
#
# Every recommendation here is computed from the models — a suggested spindle
# speed comes from the stability pockets that were actually solved for, and a
# suggested feed comes from inverting the roughness model — rather than being a
# fixed list of machining advice.




@dataclass
class Action:
    change: str
    detail: str
    gain: str = ""


@dataclass
class Assessment:
    stable: bool
    margin: float                 # ap_limit / ap, above 1 is stable
    ap_limit_mm: float
    chatter_hz: float | None
    tooth_passing_hz: float
    meets_target: bool | None
    headline: str
    state_reason: str
    finish_reason: str
    actions: list[Action] = field(default_factory=list)
    mrr_mm3_min: float = 0.0


def assess(*, res: dy.StabilityResult, ap_mm: float, ae_mm: float, n_rpm: float,
           teeth: int, fz_mm: float, feed_mm_min: float,
           rough: rg.RoughnessResult, target_ra_um: float | None,
           operation: str, diameter_mm: float, nose_radius_mm: float,
           process_factor: float, dyn: dy.ToolDynamics, Kt: float, Kr: float,
           direction: str) -> Assessment:
    ap_limit = res.limit_at(n_rpm)
    stable = ap_mm <= ap_limit
    margin = ap_limit / max(ap_mm, 1e-9)
    tpf = dy.tooth_passing_hz(n_rpm, teeth)
    fc = None if stable else dy.chatter_frequency_at(res, n_rpm)

    if stable:
        state_reason = (
            f"At {n_rpm:,.0f} rpm the limiting axial depth is {ap_limit:.2f} mm and you "
            f"are cutting {ap_mm:.2f} mm, so the cut sits {margin:.1f}× inside the "
            "stability boundary.")
        if margin < 1.3:
            state_reason += (" That is a thin margin — a worn tool or a softer clamping "
                             "will push it over.")
    else:
        state_reason = (
            f"At {n_rpm:,.0f} rpm the limiting axial depth is {ap_limit:.2f} mm but you "
            f"are cutting {ap_mm:.2f} mm, which is {1 / max(margin, 1e-9):.1f}× the limit. "
            f"Regenerative chatter is predicted at about {fc:,.0f} Hz, against a tooth "
            f"passing frequency of {tpf:,.0f} Hz.")

    meets = None if target_ra_um is None else rough.ra_expected_um <= target_ra_um
    if target_ra_um is None:
        finish_reason = (f"Expected Ra is about {rough.ra_expected_um:.2f} µm "
                         f"({rough.grade}), from a geometric {rough.ra_geometric_um:.2f} µm.")
    elif meets:
        finish_reason = (f"Expected Ra {rough.ra_expected_um:.2f} µm meets the "
                         f"{target_ra_um:.2f} µm target with room to spare.")
    else:
        finish_reason = (f"Expected Ra {rough.ra_expected_um:.2f} µm misses the "
                         f"{target_ra_um:.2f} µm target by "
                         f"{rough.ra_expected_um / target_ra_um:.1f}×.")

    quality = "bad" if meets is False else "good"
    headline = {
        (True, "good"): "Stable cut, finish within target",
        (True, "bad"): "Stable cut, but the finish misses the target",
        (False, "good"): "Chatter predicted — the finish figure will not hold",
        (False, "bad"): "Chatter predicted, and the finish misses the target",
    }[(stable, quality)]

    actions = _actions(res=res, ap_mm=ap_mm, ae_mm=ae_mm, n_rpm=n_rpm, teeth=teeth,
                       fz_mm=fz_mm, stable=stable, rough=rough,
                       target_ra_um=target_ra_um, operation=operation,
                       diameter_mm=diameter_mm, nose_radius_mm=nose_radius_mm,
                       process_factor=process_factor, dyn=dyn, Kt=Kt, Kr=Kr,
                       direction=direction, feed_mm_min=feed_mm_min)

    return Assessment(stable=stable, margin=float(margin), ap_limit_mm=float(ap_limit),
                      chatter_hz=fc, tooth_passing_hz=tpf, meets_target=meets,
                      headline=headline, state_reason=state_reason,
                      finish_reason=finish_reason, actions=actions,
                      mrr_mm3_min=dy.material_removal_rate(ap_mm, ae_mm, feed_mm_min))


def _actions(*, res, ap_mm, ae_mm, n_rpm, teeth, fz_mm, stable, rough, target_ra_um,
             operation, diameter_mm, nose_radius_mm, process_factor, dyn, Kt, Kr,
             direction, feed_mm_min) -> list[Action]:
    out: list[Action] = []

    if not stable:
        pockets = dy.stable_speed_suggestions(res, ap_mm, n_rpm)
        for p in pockets[:2]:
            new_feed = p["speed_rpm"] * teeth * fz_mm
            out.append(Action(
                change=f"Move the spindle to {p['speed_rpm']:,.0f} rpm",
                detail=(f"That pocket runs from {p['from_rpm']:,.0f} to "
                        f"{p['to_rpm']:,.0f} rpm and allows {p['limit_mm']:.2f} mm "
                        f"axial depth at its peak, against the {ap_mm:.2f} mm you need. "
                        f"Keep the feed per tooth: feed becomes {new_feed:,.0f} mm/min."),
                gain=f"{p['width_rpm']:,.0f} rpm wide, so it tolerates speed drift"))
        if not pockets:
            out.append(Action(
                change="No stable pocket at this depth anywhere in the speed range",
                detail="The depth of cut is above the critical limit at every speed, so "
                       "no choice of spindle speed will fix it on its own.",
                gain=""))

        out.append(Action(
            change=f"Reduce axial depth to {res.limit_at(n_rpm) / 1.3:.2f} mm at this speed",
            detail=(f"The limit here is {res.limit_at(n_rpm):.2f} mm; taking 30% below it "
                    "leaves margin for tool wear. Two passes at that depth beat one "
                    "chattered pass."),
            gain=f"Keeps {n_rpm:,.0f} rpm if the speed is fixed by the setup"))

        lighter = _limit_at_lower_immersion(dyn, teeth, Kt, Kr, diameter_mm, ae_mm,
                                            direction, n_rpm)
        if lighter and lighter[1] > res.limit_at(n_rpm) * 1.15:
            out.append(Action(
                change=f"Reduce radial engagement to {lighter[0]:.2f} mm",
                detail=(f"Lighter radial immersion raises the limit at this speed from "
                        f"{res.limit_at(n_rpm):.2f} to {lighter[1]:.2f} mm, because the "
                        "tooth spends less time in the cut."),
                gain="Often recovers the lost material rate through higher feed"))

        out.append(Action(
            change="If the speed is fixed, change the cutter or add damping",
            detail="A variable-pitch or variable-helix cutter breaks the regenerative "
                   "phasing that this analysis assumes. A shorter overhang raises the "
                   "natural frequency and the stiffness, which lifts the whole diagram.",
            gain="Shifts the boundary rather than working around it"))

    # Finish
    if target_ra_um is not None and rough.ra_expected_um > target_ra_um:
        if operation.startswith("Ball"):
            ae_new = rg.stepover_for_target_ra(target_ra_um, diameter_mm, process_factor)
            out.append(Action(
                change=f"Reduce the stepover to about {ae_new:.3f} mm",
                detail="Ball-nose finish is set by the scallop between passes, so "
                       "stepover is the lever, not feed.",
                gain=f"Roughly {ae_mm / max(ae_new, 1e-6):.1f}× more passes"))
        else:
            fz_new = rg.feed_for_target_ra(operation, target_ra_um, teeth=teeth,
                                           diameter_mm=diameter_mm,
                                           nose_radius_mm=nose_radius_mm,
                                           process_factor=process_factor)
            if fz_new:
                out.append(Action(
                    change=f"Reduce feed per tooth to about {fz_new:.4f} mm",
                    detail=(f"Ra scales with the square of the feed, so going from "
                            f"{fz_mm:.4f} to {fz_new:.4f} mm/tooth brings the expected "
                            f"value to the {target_ra_um:.2f} µm target. Stability is "
                            "unaffected: the lobe diagram does not depend on feed."),
                    gain=f"Feed rate becomes {n_rpm * teeth * fz_new:,.0f} mm/min"))
        if operation.startswith("Face"):
            r_new = nose_radius_mm * (rough.ra_expected_um / target_ra_um)
            out.append(Action(
                change=f"Or fit a larger nose radius, about {r_new:.2f} mm",
                detail="Ra falls inversely with nose radius, so a bigger radius or a "
                       "wiper insert meets the target without losing feed rate.",
                gain="Keeps the material removal rate"))

    if "ploughing" in rough.factors:
        out.append(Action(
            change="Raise feed per tooth above the minimum chip thickness",
            detail="Below roughly a quarter of the edge radius the edge rubs rather "
                   "than cuts, which raises roughness, forces and tool wear at the same "
                   "time. Counter-intuitively, feeding harder gives a better finish here.",
            gain="Also reduces the risk of tool breakage in micro-milling"))

    if "runout" in rough.factors:
        out.append(Action(
            change="Check and correct tool runout",
            detail=(f"Runout is spreading the marks to {rough.effective_feed_mm:.4f} mm "
                    f"instead of {fz_mm:.4f} mm, which is the same as multiplying the "
                    "feed. Re-seat the tool, clean the taper, or measure TIR with a dial "
                    "indicator."),
            gain="Recovers finish without changing any cutting parameter"))

    if stable and (target_ra_um is None or rough.ra_expected_um <= target_ra_um):
        headroom = res.limit_at(n_rpm) / max(ap_mm, 1e-9)
        out.append(Action(
            change=f"There is headroom: the limit here is {res.limit_at(n_rpm):.2f} mm",
            detail=(f"You are using {ap_mm:.2f} mm, which is {headroom:.1f}× inside the "
                    "boundary. Raising the depth in steps, checking the surface each "
                    "time, converts that margin into material rate."),
            gain=f"Up to {(headroom / 1.3):.1f}× the current MRR while keeping margin"))

    return out


def _limit_at_lower_immersion(dyn, teeth, Kt, Kr, diameter_mm, ae_mm, direction,
                              n_rpm) -> tuple[float, float] | None:
    """Re-solve the diagram at half the radial width and report the new limit."""
    ae_new = max(ae_mm / 2, diameter_mm * 0.02)
    if ae_new >= ae_mm:
        return None
    st, ex = dy.engagement_angles(diameter_mm, ae_new, direction)
    res = dy.stability_lobes(dyn, teeth=teeth, Kt=Kt, Kr=Kr, phi_st=st, phi_ex=ex,
                             freq_points=2500, n_points=800,
                             n_range=(max(200, n_rpm * 0.2), n_rpm * 3))
    return ae_new, res.limit_at(n_rpm)


